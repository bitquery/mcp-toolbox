package flowgraph

// The injection boundary. A tool of this kind runs SQL it does not write by
// hand: each chain's statement is cfg text (generated by gen_flows.py as a
// sibling of *_flow_edges, so it cannot drift from them) parsed as a Go
// text/template that reads ONLY the fields of stmtVars. Every one of those
// fields is a ClickHouse literal this package built from a validated input — a
// chain codec turned a checked address into the set array, a validated time
// into toDateTime('…','UTC'), an int into its digits. Nothing the caller or the
// returned data supplies reaches a statement except as one of those built
// literals, so the template being cfg-authored does not widen the surface.

import (
	"fmt"
	"regexp"
	"strings"
	"text/template"
)

// stmtVars are the only variables a chain's statement template may read.
type stmtVars struct {
	// SetLiteral is the address set A as a ClickHouse array literal in the
	// chain's column encoding (e.g. [toFixedString(unhex('…'),20), …]).
	SetLiteral string
	// WStart and WEnd are the fixed window bounds as toDateTime('…','UTC').
	WStart string
	WEnd   string
	// IncludeInternal is 0 or 1 (nested 'call' transfers counted when 1).
	IncludeInternal int
	// TopK is the result-row cap before the WITH TOTALS remainder.
	TopK int
	// MinUsd is an optional USD floor as a decimal literal ("0" = off).
	MinUsd string
}

// render executes a parsed statement template with the built variables. A
// template that reads a field stmtVars does not have, or is otherwise malformed,
// is caught at load time (parseStatements) — this only substitutes.
func render(t *template.Template, v stmtVars) (string, error) {
	var b strings.Builder
	if err := t.Execute(&b, v); err != nil {
		return "", fmt.Errorf("rendering the statement: %w", err)
	}
	return b.String(), nil
}

// chainCodec validates a chain's addresses and builds the ClickHouse array
// literal of an address set in that chain's column encoding. The counterparties
// a statement returns are decoded inside the statement (concat('0x',hex) /
// base58), so a codec is the write side (the set) plus the validator the result
// check and the labels read reuse.
type chainCodec interface {
	chain() string
	valid(addr string) bool
	normalize(addr string) string
	setLiteral(addrs []string) (string, error)
}

var codecs = map[string]chainCodec{}

func registerCodec(c chainCodec) { codecs[c.chain()] = c }

// codecFor is the codec of a chain, or false when the chain has none (so a
// statements block for an unsupported chain is refused at load).
func codecFor(chain string) (chainCodec, bool) {
	c, ok := codecs[strings.ToLower(strings.TrimSpace(chain))]
	return c, ok
}

// evmCodec is the shared codec of every EVM chain: a 0x-prefixed 20-byte hex
// address, written into the set as toFixedString(unhex('…'),20) so the set
// carries the column's FixedString(20) type (a String set silently loses every
// value ending in 00). The hex is lower-cased for a stable statement text; unhex
// is case-insensitive.
type evmCodec struct{ name string }

var evmAddrRe = regexp.MustCompile(`^0x[0-9a-fA-F]{40}$`)

func (c evmCodec) chain() string          { return c.name }
func (evmCodec) valid(a string) bool      { return evmAddrRe.MatchString(a) }
func (evmCodec) normalize(a string) string { return strings.ToLower(a) }

func (evmCodec) setLiteral(addrs []string) (string, error) {
	if len(addrs) == 0 {
		return "", fmt.Errorf("the address set is empty")
	}
	parts := make([]string, 0, len(addrs))
	for _, a := range addrs {
		if !evmAddrRe.MatchString(a) {
			return "", fmt.Errorf("not an EVM address: %q", a)
		}
		hex := strings.ToLower(strings.TrimPrefix(strings.ToLower(a), "0x"))
		parts = append(parts, fmt.Sprintf("toFixedString(unhex('%s'),20)", hex))
	}
	return "[" + strings.Join(parts, ", ") + "]", nil
}

// The EVM chains this kind can serve. Each shares evmCodec; the per-chain
// transfer source and statement come from cfg.
func init() {
	for _, n := range []string{"ethereum", "bsc", "matic", "arbitrum", "base", "optimism", "robinhood", "arc"} {
		registerCodec(evmCodec{n})
	}
}
