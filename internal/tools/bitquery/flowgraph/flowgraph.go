// Package flowgraph is the bitquery-flow-graph tool kind: it computes, in Go from a
// chain's transfer tables and the labels source, the funds flowing between an
// address set and its counterparties — in USD, with labels, and totalled by label
// type. It reuses the shared statement runner in internal/tools/bitquery/chainexec.
// The first tool of this kind is counterparties (BIT-16068).
//
// A tool's SQL is cfg text (generated by gen_flows.py as a sibling of the
// *_flow_edges tools); Go validates the address set, resolves the window, and
// renders only a fixed set of built literals into it (see render.go, the
// injection boundary). counterparties runs that statement, derives the
// below_cutoff remainder from its WITH TOTALS row, and (in following changes)
// attaches labels and totals funds by label type.
package flowgraph

import (
	"context"
	"fmt"
	"text/template"

	yaml "github.com/goccy/go-yaml"
	"github.com/googleapis/mcp-toolbox/internal/sources"
	"github.com/googleapis/mcp-toolbox/internal/tools"
	"github.com/googleapis/mcp-toolbox/internal/tools/bitquery/chainexec"
	"github.com/googleapis/mcp-toolbox/internal/util"
	"github.com/googleapis/mcp-toolbox/internal/util/parameters"
)

const resourceType string = "bitquery-flow-graph"

func init() {
	if !tools.Register(resourceType, newConfig) {
		panic(fmt.Sprintf("tool type %q already registered", resourceType))
	}
}

func newConfig(ctx context.Context, name string, decoder *yaml.Decoder) (tools.ToolConfig, error) {
	actual := Config{ConfigBase: tools.ConfigBase{Name: name}}
	if err := decoder.DecodeContext(ctx, &actual); err != nil {
		return nil, err
	}
	return actual, nil
}

// Config is the kind's configuration. Like the risk report, a tool names one chain
// source per call and the labels source; ChainSources maps each supported chain to
// its transfer source. The method parameters are built in a following change.
type Config struct {
	tools.ConfigBase `yaml:",inline"`
	Type             string            `yaml:"type" validate:"required"`
	Source           string            `yaml:"source" validate:"required"`
	ChainSources     map[string]string `yaml:"chainSources" validate:"required"`
	LabelsSource     string            `yaml:"labelsSource" validate:"required"`
	// Statements maps a chain to the SQL template (generated by gen_flows.py) that
	// computes its counterparties. Each is a Go text/template read only by
	// render; see render.go for the fixed variable set and why the template being
	// cfg text does not widen the injection surface. A chain with a statement must
	// also have a chainSource and a codec (parseStatements checks both at load).
	Statements map[string]string `yaml:"statements"`
	// Budget bounds a call: its deadline, and the per-statement time and rows.
	// Zero fields take the defaults in Budget.withDefaults.
	Budget      Budget                 `yaml:"budget"`
	Parameters  parameters.Parameters  `yaml:"parameters"`
	Annotations *tools.ToolAnnotations `yaml:"annotations,omitempty"`
}

var _ tools.ToolConfig = Config{}

func (cfg Config) ToolConfigType() string {
	return resourceType
}

// sqlSource is the labels source (directory.labels), queried in Go over the
// counterparty set.
type sqlSource interface {
	RunSQL(context.Context, string, parameters.ParamValues) (any, error)
}

// paramTypes are the parameters this kind reads, with their types; addresses and
// chain are required, the rest optional. A cfg parameter not listed here is
// refused at load, so the manifest cannot drift from what Go reads.
var paramTypes = map[string]string{
	"addresses":          "string",
	"chain":              "string",
	"group_by":           "string",
	"after_time":         "string",
	"before_time":        "string",
	"include_internal":   "integer",
	"min_usd":            "float",
	"limit":              "integer",
	"cursor":             "string",
	"label_type":         "string",
	"exclude_label_type": "string",
	"format":             "string",
}

func (cfg Config) Initialize(ctx context.Context) (tools.Tool, error) {
	if cfg.Description == "" {
		return nil, fmt.Errorf("description is required for tool %q", cfg.Name)
	}
	stmts, err := parseStatements(cfg)
	if err != nil {
		return nil, err
	}
	// The default source must be one of the chain sources, as the risk report
	// requires: ValidateSource then confirms the resolved one is an http source.
	foundSource := false
	for _, name := range cfg.ChainSources {
		if name == cfg.Source {
			foundSource = true
		}
	}
	if !foundSource {
		return nil, fmt.Errorf("tool %q: source %q must be one of chainSources", cfg.Name, cfg.Source)
	}
	allParameters, paramManifest, err := parameters.ProcessParameters(nil, cfg.Parameters)
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	for _, p := range allParameters {
		want, ok := paramTypes[p.GetName()]
		if !ok {
			return nil, fmt.Errorf("tool %q: parameter %q is not read by this kind", cfg.Name, p.GetName())
		}
		if p.GetType() != want {
			return nil, fmt.Errorf("tool %q: parameter %q must be of type %s, not %s", cfg.Name, p.GetName(), want, p.GetType())
		}
		seen[p.GetName()] = true
	}
	for _, req := range []string{"addresses", "chain"} {
		if !seen[req] {
			return nil, fmt.Errorf("tool %q: parameter %q is required", cfg.Name, req)
		}
	}

	t := Tool{
		BaseTool: tools.NewBaseTool(
			cfg,
			tools.GetAnnotationsOrDefault(cfg.Annotations, tools.NewReadOnlyAnnotations),
			tools.Manifest{Description: cfg.Description, Parameters: paramManifest, AuthRequired: cfg.AuthRequired},
			allParameters,
		),
		stmts:  stmts,
		budget: cfg.Budget.withDefaults(),
	}
	// The sources come from the server at start-up. Offline flows (skills
	// generation) initialize tools without them and never invoke one; a call is
	// refused then (run checks t.chains).
	if lookup, ok := tools.SourceLookupFromContext(ctx); ok {
		t.chains = map[string]chainexec.HTTPSource{}
		for chain, name := range cfg.ChainSources {
			s, ok := lookup.GetSource(name)
			if !ok {
				return nil, fmt.Errorf("tool %q: unable to retrieve source %q for chain %s", cfg.Name, name, chain)
			}
			hs, ok := s.(chainexec.HTTPSource)
			if !ok {
				return nil, fmt.Errorf("tool %q: source %q for chain %s is not an http source", cfg.Name, name, chain)
			}
			t.chains[chain] = hs
		}
		s, ok := lookup.GetSource(cfg.LabelsSource)
		if !ok {
			return nil, fmt.Errorf("tool %q: unable to retrieve labels source %q", cfg.Name, cfg.LabelsSource)
		}
		ls, ok := s.(sqlSource)
		if !ok {
			return nil, fmt.Errorf("tool %q: labels source %q cannot run SQL", cfg.Name, cfg.LabelsSource)
		}
		t.labels = ls
	}
	return t, nil
}

// parseStatements compiles every chain's statement template once, at load, so a
// malformed template (or one for a chain with no codec or no chainSource) stops
// the whole cfg from loading rather than failing a call. A tool with no
// statements is allowed to load (the skeleton case); an invoke then refuses the
// chain.
func parseStatements(cfg Config) (map[string]*template.Template, error) {
	out := make(map[string]*template.Template, len(cfg.Statements))
	for chain, text := range cfg.Statements {
		if _, ok := codecFor(chain); !ok {
			return nil, fmt.Errorf("tool %q: statements has chain %q, which this kind has no codec for", cfg.Name, chain)
		}
		if _, ok := cfg.ChainSources[chain]; !ok {
			return nil, fmt.Errorf("tool %q: statements has chain %q, which is not in chainSources", cfg.Name, chain)
		}
		t, err := template.New(chain).Option("missingkey=error").Parse(text)
		if err != nil {
			return nil, fmt.Errorf("tool %q: statements[%s]: %w", cfg.Name, chain, err)
		}
		// Trial-render with placeholder literals: a template that reads a field
		// stmtVars does not have parses cleanly but fails at execute, so catch it
		// here at load rather than on every call.
		if _, err := render(t, stmtVars{SetLiteral: "[]", WStart: "''", WEnd: "''", MinUsd: "0"}); err != nil {
			return nil, fmt.Errorf("tool %q: statements[%s]: %w", cfg.Name, chain, err)
		}
		out[chain] = t
	}
	return out, nil
}

var _ tools.Tool = Tool{}

type Tool struct {
	tools.BaseTool[Config]
	// stmts is the compiled statement template of each configured chain.
	stmts map[string]*template.Template
	// budget bounds a call (with defaults applied); chains and labels are the
	// resolved sources (nil in an offline init, where a call is refused).
	budget Budget
	chains map[string]chainexec.HTTPSource
	labels sqlSource
}

func (t Tool) GetSourceName() string {
	return t.Cfg.Source
}

func (t Tool) ToConfig() tools.ToolConfig {
	return t.Cfg
}

func (t Tool) ValidateSource(source sources.Source) error {
	// The runner (chainexec.Exec) issues HTTP statements against the chain source,
	// so the resolved source must be an http source — the same check the risk report
	// makes, and the first use of chainexec by this kind.
	if _, ok := source.(chainexec.HTTPSource); !ok {
		return fmt.Errorf("invalid source for %q tool: source %q is not an http source", t.Cfg.Type, t.Cfg.Source)
	}
	return nil
}

func (t Tool) Invoke(ctx context.Context, _ sources.Source, params parameters.ParamValues, _ tools.AccessToken) (any, util.ToolboxError) {
	return t.run(ctx, params.AsMap())
}
